def gfile(name, per, grams, hours, body="", model="Bambu Lab P1S", plate="p1", pid="3DP0002", verified=False):
    path = os.path.join(D, name)
    open(path, "w").write("; generated by test\n; filament used [g] = %s\nM83\nG28\n" % grams + (body or ";LAYER_CHANGE\nG0 X60 Y60\nG1 X61 Y60 E0.5\nG1 X80 Y60 E1\nG1 X80 Y80 E1\n;LAYER_CHANGE\nG1 X10 Y10 E1\n"))
    f = print_files.add(path, name, pid, model, "", per, "", "t", "boss", "PLA", grams, hours, source="plan", plate_id=plate)
    slicecheck.confirm(f["id"], model, "boss")
    if verified:
        print_files.verify(f["id"], True, "boss")
    return print_files.get(f["id"])

