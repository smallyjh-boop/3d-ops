# v2.52：一件成品要打几盘的打印方案（盘 1 主体件、盘 2 小零件）→ 生产每一盘都排单、各用自己的文件 / 打印机要求 / 用料，
# 凑齐一整套才进成品库存（qty_done），某一盘失败只有这一盘回到队列；一盘的产品照旧
import os as _os
T = _os.environ["T3D_TMP"]; APP = _os.environ["T3D_APP"]
import json, os, sys, shutil, sqlite3
D = T + "/m_multiplate252"; shutil.rmtree(D, ignore_errors=True); shutil.copytree(T + "/v13", D)
c0 = sqlite3.connect(D + "/app.db"); c0.execute("delete from users"); c0.commit(); c0.close()
os.environ["LH_DATA_DIR"] = D; sys.path.insert(0, APP)
E_ = 0
def ok(b, m):
    global E_; print(("OK  " if b else "ERR ") + m); E_ += (not b)
import app as A
from core import db, store, production, print_files, orders as orders_mod, chain, inventory
from core.config import load_config, save_config
db.create_user("boss", "secret123", "owner", "Boss"); db.create_user("pong", "secret123", "production", "Pong")
C = A.app.test_client(); C.post("/api/auth/login", json={"username": "boss", "password": "secret123"})
PC = A.app.test_client(); PC.post("/api/auth/login", json={"username": "pong", "password": "secret123"})

# ---------- 打印机：P1S（有 AMS，#0）+ K1C（没有，#1） ----------
save_config({"printers": [{"code": "P1S-01", "name": "Bambu Lab P1S", "g_per_h": 22, "enabled": True, "tech": "fdm"},
                          {"code": "K1C-01", "name": "Creality K1C", "g_per_h": 18, "enabled": True, "tech": "fdm"}],
             "stock_auto_use": False})
CONFIRM = {"bed_clear": True, "material": True}

# ---------- 产品：两盘的方案（盘 1 主体件 两色 一盘 1 套；盘 2 小零件 单色黑 一盘 2 套） ----------
PID = "3DP0002"
p = store.load(PID)
p["variants"] = [{"opt1_zh": "白色", "opt2_zh": "", "sku": "3DP0002-WH", "grams": 60, "hours": 4},
                 {"opt1_zh": "黑色", "opt2_zh": "", "sku": "3DP0002-BK", "grams": 60, "hours": 4}]
p["print_plans"] = {"": {"plates": [
    {"id": "p1", "name": "主体件", "printer": "Bambu Lab P1S", "layer_height": 0.2, "sets": 1, "items": [],
     "slots": [{"slot": 1, "material": "PLA", "colour": ""}, {"slot": 2, "material": "PLA", "colour": "黑色"}],
     "sliced": {"filaments": [{"slot": 1, "grams": 40}, {"slot": 2, "grams": 10}], "hours": 3, "purge_g": 5, "changes": 20}},
    {"id": "p2", "name": "小零件", "printer": "Creality K1C", "layer_height": 0.2, "sets": 2, "items": [],
     "slots": [{"slot": 1, "material": "PLA", "colour": "黑色"}],
     "sliced": {"filaments": [{"slot": 1, "grams": 8}], "hours": 1, "purge_g": 0, "changes": 0}}], "schemes": {}}}
store.save(p)
from core import modules
pp = modules.public("model")
jp = pp.job_plates(PID, "3DP0002-WH", "白色")
ok(len(jp) == 2 and jp[0]["multicolor"] and not jp[1]["multicolor"] and jp[1]["sets"] == 2, f"job_plates {[(x['plate_id'], x['sets'], x['multicolor']) for x in jp]}")
ok(abs(jp[0]["grams"] - 55) < 0.2 and jp[1]["grams"] == 8 and jp[1]["colours"][0]["colour"] == "黑色", f"plate grams incl. purge {jp[0]['grams']} {jp[1]['colours']}")
ok(production.plate_text(jp[0]) == "盘 1/2 · 主体件" and "盘" not in production.plate_text(jp[0], "th"), "plate label zh / th")

# ---------- 文件 ↔ 盘：每盘自己的切片文件 ----------
gpath = os.path.join(D, "p2.gcode")
open(gpath, "w").write("; generated by test\nG28\nG1 X10 Y10\n")
f2 = print_files.add(gpath, "3DP0002_p2.gcode", PID, "Creality K1C", "", 2, "", "plate 2", "boss", "PLA", 8, 1.0,
                     source="plan", plate_id="p2")
db.conn().execute("UPDATE print_files SET status='verified' WHERE id=?", (f2["id"],)); db.conn().commit()
from modules.prod import slicecheck
slicecheck.confirm(f2["id"], "Creality K1C", "boss")
ok(f2["plate_id"] == "p2", "print file remembers its plate")
ok([x["id"] for x in print_files.candidates(PID, "3DP0002-WH", "Creality K1C", usable_only=False, plate_id="p2")] == [f2["id"]]
   and not print_files.candidates(PID, "3DP0002-WH", "Creality K1C", usable_only=False, plate_id="p1"), "candidates filtered by plate")
ov = C.get("/api/files?q=3DP0002").get_json()
sl = next(x for r in ov["rows"] for x in r["slices"] if x["id"] == f2["id"])
ok(sl.get("plate") == {"no": 2, "total": 2, "name": "小零件"}, f"files overview shows plate {sl.get('plate')}")

# ---------- 备货 4 套：盘 1 要打 4 次、盘 2（一盘 2 套）只要 2 次 ----------
job = production.create_job(PID, "3DP0002-WH", 4, kind="stock", user="boss")
JID = job["id"]
jl = lambda: next(x for x in production.list_jobs() if x["id"] == JID)
pl = {v["plate_id"]: v for v in jl()["plates"]}
ok(jl()["multi_plate"] == 2 and set(pl) == {"p1", "p2"}, "job has work for both plates")
ok(pl["p1"]["prints_left"] == 4 and pl["p2"]["prints_left"] == 2, f"sets=2 plate needs half the prints {pl['p1']['prints_left']} {pl['p2']['prints_left']}")
ok(pl["p1"]["printer"] == 0, f"multicolour plate scheduled only on AMS printer {pl['p1']['printer']}")
ok(pl["p2"]["printer"] in (0, 1) and pl["p2"]["planned_end"], "single-colour plate scheduled too")
ok(pl["p1"]["label"] == "盘 1/2 · 主体件" and pl["p1"].get("ams_line", "").startswith("AMS") and not pl["p2"].get("ams_line"), "plate labels + AMS line per plate")
b = C.get("/api/production").get_json()
cards = [c for l in b["lanes"] for c in l["queue"]] + b["unassigned"]
mine = [c for c in cards if c["id"] == JID]
ok(sorted(c["plate"]["plate_id"] for c in mine) == ["p1", "p2"], f"board shows a card per plate {[c.get('plate', {}).get('plate_id') for c in mine]}")
p2card = next(c for c in mine if c["plate"]["plate_id"] == "p2")
ok(p2card["plan"] is None or p2card["plan"]["per_plate"] == 2, "plate card plan uses plate sets")
# 只有盘 2 文件在 K1C 上 → 排单时盘 2 优先放 K1C（有文件）
ok(pl["p2"]["printer"] == 1, f"plate 2 goes to the printer that has its file {pl['p2']['printer']}")
# 把 K1C 设成唯一能用的机器：盘 1 没地方排（只能 AMS），盘 2 照排
cfg = load_config(); cfg["printers"][0]["enabled"] = False; save_config(cfg)
production.schedule()
pl = {v["plate_id"]: v for v in jl()["plates"]}
ok(pl["p1"]["printer"] is None and pl["p2"]["printer"] == 1, f"no AMS printer → plate 1 unassigned, plate 2 still on K1C {pl['p1']['printer']} {pl['p2']['printer']}")
cfg = load_config(); cfg["printers"][0]["enabled"] = True; save_config(cfg)
production.schedule()

# ---------- 开始：盘 1 不能放 K1C；send options 只列这一盘的文件 ----------
try:
    production.start_run(JID, 1, send=False, user="boss", confirm=CONFIRM, plate="p1"); ok(False, "multicolour plate on K1C refused")
except ValueError as e:
    ok("AMS" in str(e) and "盘 1/2" in str(e), f"multicolour plate on K1C refused: {e}")
so = PC.get(f"/api/jobs/{JID}/send-options?plate=p2&printer=1").get_json()
ok(so["plate"]["plate_id"] == "p2" and so["capacity"] == 2 and [f["id"] for f in so["files"]] == [f2["id"]] and not so["colours"], f"send options for plate 2 {so.get('capacity')}")
so1 = PC.get(f"/api/jobs/{JID}/send-options?plate=p1&printer=0").get_json()
ok(so1["plate"]["plate_id"] == "p1" and len(so1["colours"]) == 2 and not so1["files"], "send options for plate 1: AMS colours, no plate-2 file")

stock0 = production.stock_qty("3DP0002-WH")
r1 = PC.post(f"/api/jobs/{JID}/start", json={"printer": 0, "send": False, "plate": "p1", "confirm": CONFIRM}).get_json()
ok(r1.get("run_id") and r1["count"] == 1 and r1["plate"]["plate_id"] == "p1", f"start plate 1 {r1}")
run1 = dict(db.conn().execute("SELECT * FROM print_runs WHERE id=?", (r1["run_id"],)).fetchone())
cols1 = json.loads(run1["colors"])
ok(run1["plate_id"] == "p1" and run1["plate_no"] == 1 and len(cols1) == 2 and abs(sum(x["grams"] for x in cols1) - 55) < 0.3, f"run 1 per-colour usage of plate 1 {cols1}")
ok(jl()["status"] == "printing", "job printing while a plate prints")
# 盘 1 在打的时候盘 2 还能排、还能开始（另一台打印机）
pl = {v["plate_id"]: v for v in jl()["plates"]}
ok(pl["p1"]["run_id"] == r1["run_id"] and pl["p2"]["run_id"] is None and pl["p2"]["printer"] == 1, "plate 2 still queued while plate 1 prints")
b = C.get("/api/production").get_json()
lane0 = b["lanes"][0]
ok(any(r["id"] == r1["run_id"] and r.get("plate_label") == "盘 1/2 · 主体件" for r in lane0["runs"]), "board run card shows the plate")
try:
    production.start_run(JID, 1, send=False, user="boss", confirm=CONFIRM, plate="p1"); ok(False, "same plate twice refused")
except ValueError as e:
    ok("已经在打" in str(e), f"same plate twice refused: {e}")
r2 = production.start_run(JID, 1, send=False, user="boss", confirm=CONFIRM, plate="p2", file_id=f2["id"])
run2 = dict(db.conn().execute("SELECT * FROM print_runs WHERE id=?", (r2["run_id"],)).fetchone())
ok(r2["count"] == 2 and run2["file_id"] == f2["id"] and run2["color"] == "黑色" and json.loads(run2["colors"])[0]["colour"] == "黑色",
   f"plate 2 run uses its own file + colour {run2['file_id']} {run2['color']}")

# ---------- 打完盘 1：还没凑齐 → 不加库存 ----------
production.finish_run(r1["run_id"], "boss")
j = jl()
ok(production.stock_qty("3DP0002-WH") == stock0 and j["qty_done"] == 0, f"plate 1 alone adds no stock {production.stock_qty('3DP0002-WH')} {j['qty_done']}")
ok(j["status"] == "printing" and j["run_id"] == r2["run_id"], "job still printing (plate 2 on K1C)")
try:
    production.start_run(JID, 0, send=False, user="boss", confirm=CONFIRM, plate="p1", file_id=f2["id"]); ok(False, "wrong plate file refused")
except ValueError as e:
    ok("不是这一盘" in str(e), f"plate 1 can't use plate 2 file: {e}")
# ---------- 打完盘 2（2 套零件）：凑齐 1 套 → 库存 +1 ----------
production.finish_run(r2["run_id"], "boss")
j = jl()
pl = {v["plate_id"]: v for v in j["plates"]}
ok(production.stock_qty("3DP0002-WH") == stock0 + 1 and j["qty_done"] == 1, f"both plates → +1 complete set {production.stock_qty('3DP0002-WH')} {j['qty_done']}")
ok(j["status"] == "todo" and pl["p1"]["prints_left"] == 3 and pl["p2"]["prints_left"] == 1, f"remaining prints {pl['p1']['prints_left']} {pl['p2']['prints_left']}")
ok(pl["p1"]["prints"] == 1 and pl["p2"]["prints"] == 1 and j["plates_done"] == 2, "per-plate print counts")

# ---------- 盘 1 失败：只有盘 1 回到队列 ----------
r3 = production.start_run(JID, 0, send=False, user="boss", confirm=CONFIRM, plate="p1")
production.fail_run(r3["run_id"], "翘边 / 首层不粘", "", "boss")
j = jl()
pl = {v["plate_id"]: v for v in j["plates"]}
ok(pl["p1"]["run_id"] is None and pl["p1"]["fails"] == 1 and pl["p1"]["prints_left"] == 3 and pl["p1"]["printer"] == 0, "failed plate re-queued")
ok(pl["p2"]["fails"] == 0 and pl["p2"]["prints_left"] == 1 and j["qty_done"] == 1 and j["status"] == "todo", "other plate untouched")
ok(db.conn().execute("SELECT COUNT(*) FROM failures WHERE run_id=?", (r3["run_id"],)).fetchone()[0] == 1, "failure recorded")
# 撤销只撤这一盘
r4 = production.start_run(JID, 1, send=False, user="boss", confirm=CONFIRM, plate="p2")
production.cancel_run(r4["run_id"], "boss")
pl = {v["plate_id"]: v for v in jl()["plates"]}
ok(pl["p2"]["run_id"] is None and pl["p2"]["prints_left"] == 1 and jl()["status"] == "todo", "cancel releases just that plate")

# ---------- 打完剩下的：盘 1 ×3、盘 2 ×1 → 4 套齐了，备货任务完成 ----------
for _ in range(3):
    rr = production.start_run(JID, 0, send=False, user="boss", confirm=CONFIRM, plate="p1"); production.finish_run(rr["run_id"], "boss")
ok(jl()["qty_done"] == 2 and production.stock_qty("3DP0002-WH") == stock0 + 2, f"plate 1 ahead: only sets plate 2 covers count {jl()['qty_done']}")
rr = production.start_run(JID, 1, send=False, user="boss", confirm=CONFIRM, plate="p2"); production.finish_run(rr["run_id"], "boss")
j = next(x for x in production.list_jobs() if x["id"] == JID)
ok(j["qty_done"] == 4 and j["status"] == "done" and production.stock_qty("3DP0002-WH") == stock0 + 4, f"all 4 sets → stock +4, job done {j['qty_done']} {j['status']}")

# ---------- 订单任务：3 套（盘 2 一盘 2 套 → 打 2 次 = 4 套零件，多出 1 套零件不算成品） ----------
orders_mod.upsert([{"platform": "manual", "order_no": "MP-1", "status": "to_ship", "items": [{"sku": "3DP0002-WH", "qty": 3}]}], source="test")
chain.order_changed("t")
production.generate("t")
oid = db.conn().execute("SELECT id FROM orders WHERE order_no='MP-1'").fetchone()["id"]
oj = production.list_jobs(order_id=oid)
ok(len(oj) == 1 and oj[0]["multi_plate"] == 2 and {v["plate_id"]: v["prints_left"] for v in oj[0]["plates"]} == {"p1": 3, "p2": 2}, f"order job split into plates {[(v['plate_id'], v['prints_left']) for v in oj[0].get('plates') or []]}")
OJ = oj[0]["id"]
s0 = production.stock_qty("3DP0002-WH")
for _ in range(2):
    rr = production.start_run(OJ, 1, send=False, user="boss", confirm=CONFIRM, plate="p2"); production.finish_run(rr["run_id"], "boss")
for _ in range(3):
    rr = production.start_run(OJ, 0, send=False, user="boss", confirm=CONFIRM, plate="p1"); production.finish_run(rr["run_id"], "boss")
oj = production.list_jobs(order_id=oid)[0]
ok(oj["qty_done"] == 3 and oj["status"] == "post" and production.stock_qty("3DP0002-WH") == s0, f"order job complete, spare plate-2 parts not stock {oj['qty_done']} {oj['status']}")
ok(any("盘 2/2" in x["action"] for x in orders_mod.get_log(oid)), "order log mentions the plate")
# 退回重打：每一盘也重来
production.set_status(OJ, "todo", "boss")
production.schedule()
oj = production.list_jobs(order_id=oid)[0]
ok(oj["qty_done"] == 0 and {v["plate_id"]: v["prints_left"] for v in oj["plates"]} == {"p1": 3, "p2": 2}, "reprint resets plate progress")

# ---------- 一盘的产品照旧 ----------
P1 = "3DP0015"
sku1 = store.load(P1)["variants"][0]["sku"]
ok(not pp.job_plates(P1, sku1), "single-plate product: no plate split")
j1 = production.create_job(P1, sku1, 3, kind="stock", user="boss")
x = next(v for v in production.list_jobs() if v["id"] == j1["id"])
ok(not x.get("plates") and not x["multi_plate"] and x["printer"] is not None, "single-plate job scheduled as before")
s1 = production.stock_qty(sku1)
rr = production.start_run(j1["id"], x["printer"], 3, send=False, user="boss", confirm=CONFIRM)
ok(rr["count"] == 3 and rr["plate"] is None, "single-plate run as before")
production.finish_run(rr["run_id"], "boss")
x = next(v for v in production.list_jobs() if v["id"] == j1["id"])
ok(x["qty_done"] == 3 and x["status"] == "done" and production.stock_qty(sku1) == s1 + 3, "single-plate finish adds stock as before")
# 一盘的方案（保存过，只有一盘）也照旧
p1 = store.load(P1); p1["print_plans"] = {"": {"plates": [{"id": "p1", "name": "", "printer": "Bambu Lab P1S", "layer_height": 0.2, "sets": 1, "items": [],
                                                           "slots": [{"slot": 1, "material": "PLA", "colour": ""}]}]}}
store.save(p1)
ok(not pp.job_plates(P1, sku1), "saved one-plate plan: no split")
# 方案改回一盘：还没开始的盘删掉，任务照旧整件打
p = store.load(PID); p["print_plans"][""]["plates"] = p["print_plans"][""]["plates"][:1]; store.save(p)
production.schedule()
oj = production.list_jobs(order_id=oid)[0]
ok(not oj["multi_plate"] and not oj.get("plates") and oj["printer"] is not None, "plan back to one plate → job back to whole-item printing")
ok(db.conn().execute("SELECT COUNT(*) FROM job_plates WHERE job_id=?", (OJ,)).fetchone()[0] == 0, "plate rows removed")

# ---------- 界面 ----------
js = open(os.path.join(APP, "modules/prod/ui/prod.js"), encoding="utf-8").read()
ok("data-plate" in js and "plateLine" in js, "job card shows plate + passes plate to start")
th = json.load(open(os.path.join(APP, "modules/prod/i18n/th.json"), encoding="utf-8"))
ok(all(not any("一" <= ch <= "鿿" for ch in v) for v in th.values()), "th.json has no Chinese")
print("ERRORS", E_)
sys.exit(1 if E_ else 0)
