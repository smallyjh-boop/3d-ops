  const OV = window.I18N_OVERRIDES || {};
  Object.assign(TH, OV.subs || {});
  const KEYS = Object.keys(TH).sort((a, b) => b.length - a.length);
  const HAS_ZH = /[一-鿿]/;

  function t(s) {
    if (lang !== "th" || !s || !HAS_ZH.test(s)) return s;
    if (TH[s.trim()]) return s.replace(s.trim(), TH[s.trim()]);
    for (const k of KEYS) if (s.includes(k)) s = s.split(k).join(TH[k]);
    return s;
  }

  function skip(node) {
    const el = node.nodeType === 1 ? node : node.parentElement;
    if (!el) return true;
    if (el.closest("[data-notr], script, style")) return true;
    return node.nodeType === 3 && el.tagName === "TEXTAREA";
  }

  function translate(root) {
    if (lang !== "th" || !root) return;
    if (root.nodeType === 3) {
      if (!skip(root)) { const v = t(root.nodeValue); if (v !== root.nodeValue) root.nodeValue = v; }
      return;
    }
    if (root.nodeType !== 1 || skip(root)) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    let n = root;
    while (n) {
      if (n.nodeType === 3) {
        if (HAS_ZH.test(n.nodeValue) && !skip(n)) { const v = t(n.nodeValue); if (v !== n.nodeValue) n.nodeValue = v; }
      } else if (n.nodeType === 1 && !skip(n)) {
        for (const a of ["placeholder", "title"]) {
          const v = n.getAttribute(a);
          if (v && HAS_ZH.test(v)) n.setAttribute(a, t(v));
        }
      }
      n = walker.nextNode();
    }
  }

